// The files that make the skill self-proving and installable: scripts/ (audit + regression tests),
// ci/github-workflow.yml and README.md with the spec2skill credit.
// oxlint-disable import/default -- `?raw` imports are the files' text, not the modules
import auditMjs from './assets/scripts/audit.mjs?raw';
import auditTest from './assets/scripts/audit-test.mjs?raw';
import kitTest from './assets/scripts/kit-test.mjs?raw';
import { label } from './sanitize';
import type { FileTree, SkillContext } from './types';

export function metaFiles({ model, slug, env, examples }: SkillContext): FileTree {
  const title = label(model.source.title);
  const ci = [
    `# CI for the ${slug} skill: regression tests, every worked example (dry run) and the audit.`,
    '# Move this file to .github/workflows/ to run it on GitHub.',
    `name: ${slug} skill`,
    'on: [push, pull_request]',
    'jobs:',
    '  audit:',
    '    runs-on: ubuntu-latest',
    '    strategy:',
    '      matrix:',
    '        node: [20, 22]',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '      - uses: actions/setup-node@v4',
    '        with:',
    '          node-version: ${{ matrix.node }}',
    '      - run: node --test scripts/*.test.mjs',
    ...examples.map(({ dir }) => `      - run: node ${dir}run.mjs`),
    '      - run: node scripts/audit.mjs .',
  ];
  const readme = [
    `# ${slug}`,
    '',
    `An agent skill for the ${title}: read [SKILL.md](SKILL.md) first.`,
    '',
    '## Install',
    '',
    '```sh',
    `mkdir -p .claude/skills && unzip ${slug}-skill.zip -d .claude/skills/   # or your agent's skills directory`,
    `node .claude/skills/${slug}/scripts/audit.mjs .claude/skills/${slug}   # prints "audit passed"`,
    '```',
    '',
    `Live calls read ${model.source.kind === 'mcp' ? `the server endpoint from \`${env}_URL\`` : `credentials from \`${env}_*\` variables (see [references/auth.md](references/auth.md)) and an optional \`${env}_BASE_URL\``}. Examples and the audit never call the API.`,
    '',
    '## Layout',
    '',
    '- `SKILL.md`: the one idea, the workflow and the quality bar; `references/`: one page per resource plus auth, workflows, pagination and errors.',
    '- `kit/`: `operations.json` and the code calls are built from; `examples/`: worked examples (each `examples/*/run.mjs` runs with plain `node`).',
    '- `scripts/`: `audit.mjs` and the regression tests (`node --test scripts/*.test.mjs`); `evals/evals.json`: graded prompts; `ci/github-workflow.yml`: runs all of it.',
    '',
    `Generated by spec2skill from ${title} (source hash ${model.hash.slice(0, 12)}).`,
  ];
  return {
    'scripts/audit.mjs': auditMjs,
    'scripts/audit.test.mjs': auditTest,
    'scripts/kit.test.mjs': kitTest,
    'ci/github-workflow.yml': `${ci.join('\n')}\n`,
    'README.md': `${readme.join('\n')}\n`,
  };
}
