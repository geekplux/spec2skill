// The examples/ gallery: the generated skill of every built-in sample.
//   pnpm gallery          writes each skill with write-skill.mjs, runs its audit (which also writes the
//                         examples' dry-run plan.json files) and tests, then replaces examples/ with the result
//   pnpm gallery --check  does the same in a temp dir and exits 1 if anything differs from examples/
import { execFileSync, execSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// [sample id, source, what its skill shows]
const SAMPLES = [
  ['tasks', 'Tasks API sample (OpenAPI 3.1)', '22 operations in 5 resources; ids feed through `listProjects -> listTasks -> getTask`; bearer auth; cursor pagination'],
  ['petstore', 'Swagger Petstore (Swagger 2.0)', '16 operations over pets and users; `findPetsByStatus -> getPetById`; API key and OAuth2; a multipart upload'],
  ['filesystem', 'Filesystem MCP server (recorded `tools/list`)', '14 MCP tools with annotations; `list_allowed_directories -> search_files -> read_text_file`; destructive tools need confirmation'],
];
const root = fileURLToPath(new URL('..', import.meta.url));
const gallery = join(root, 'examples');

/** Every file under `dir`, as sorted paths relative to it. */
export const filesUnder = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { recursive: true }).map(String).filter((p) => statSync(join(dir, p)).isFile()).map((p) => p.replaceAll('\\', '/')).toSorted()
    : [];

/** What differs between two directories: `+ path` only in `fresh`, `- path` only in `kept`, `~ path` changed. */
export function driftBetween(fresh, kept) {
  const a = filesUnder(fresh);
  const b = filesUnder(kept);
  const out = [...a.filter((p) => !b.includes(p)).map((p) => `+ ${p}`), ...b.filter((p) => !a.includes(p)).map((p) => `- ${p}`)];
  for (const p of a.filter((x) => b.includes(x)))
    if (!readFileSync(join(fresh, p)).equals(readFileSync(join(kept, p)))) out.push(`~ ${p}`);
  return out.toSorted((x, y) => x.slice(2).localeCompare(y.slice(2)));
}

export const readme = (rows) =>
  [
    '# Example skills',
    '',
    'Three complete agent skills, generated by spec2skill from its built-in samples. Each is exactly what the web app\'s **Download .zip** and `spec2skill --sample <id>` write: `SKILL.md`, a tested `kit/`, `references/`, two worked `examples/`, audit `scripts/`, `evals/evals.json` and a `ci/` workflow.',
    '',
    '| Skill | Built from | What it shows | Prove it |',
    '| --- | --- | --- | --- |',
    ...rows.map(([slug, source, shows]) => `| [${slug}](${slug}/SKILL.md) | ${source} | ${shows} | \`node examples/${slug}/scripts/audit.mjs examples/${slug}\` |`),
    '',
    '## Try one',
    '',
    '```sh',
    'cd examples/tasks-api',
    'node --test scripts/*.test.mjs                    # the kit\'s regression tests',
    'node examples/list-projects-to-get-task/run.mjs   # a worked example: writes its dry-run plan.json, calls nothing',
    'node scripts/audit.mjs .                          # one line per check, then "audit passed"',
    '```',
    '',
    'Regenerated with `pnpm gallery`; do not edit by hand (`pnpm gallery --check` fails on any drift).',
    '',
  ].join('\n');

function main() {
  const check = process.argv.includes('--check');
  const tmp = mkdtempSync(join(tmpdir(), 'spec2skill-gallery-'));
  try {
    const rows = SAMPLES.map(([id, source, shows]) => {
      execFileSync(process.execPath, [join(root, 'scripts/write-skill.mjs'), id, join(tmp, id)], { stdio: 'ignore' });
      const slug = /^name: ([a-z0-9-]+)$/m.exec(readFileSync(join(tmp, id, 'SKILL.md'), 'utf8'))?.[1];
      if (!slug) throw new Error(`gallery: no name in the ${id} skill's frontmatter`);
      renameSync(join(tmp, id), join(tmp, slug));
      execSync('node scripts/audit.mjs . && node --test scripts/*.test.mjs', { cwd: join(tmp, slug), stdio: ['ignore', 'ignore', 'inherit'] });
      console.log(`${slug}: audit passed, tests passed`);
      return [slug, source, shows];
    });
    writeFileSync(join(tmp, 'README.md'), readme(rows));
    if (check) {
      const drift = driftBetween(tmp, gallery);
      if (drift.length) {
        console.error(`gallery drift (run pnpm gallery):\n${drift.join('\n')}`);
        process.exitCode = 1;
      } else console.log(`gallery up to date (${rows.length} skills)`);
      return;
    }
    rmSync(gallery, { recursive: true, force: true });
    cpSync(tmp, gallery, { recursive: true });
    console.log(`wrote ${rows.length} skills to examples/`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
