// The README demo (docs/media/demo.gif), captured from the real app on the built-in samples at 1280x800
// in the light theme, in three scenes:
//   1. load    switching from Petstore to the Tasks API sample plays the load sequence (DESIGN.md 7): the
//              cards rise column by column, the links fade in, the strongest workflow draws left to right
//              and its stop discs pop. Every animation is paused and sought to each frame's time, so the
//              frames show the real sequence at its real pace, whatever the machine's speed.
//   2. hover   getTask under the pointer: its feed links in ink, the rest faded, the operation card.
//   3. skill   the card's In skill link opens references/tasks.md in the skill browser under the map,
//              beside the audit.
// Frames go to docs/media/demo/NNN.png (gitignored; regenerated by this script); with the system ffmpeg
// they are assembled into docs/media/demo.gif (960 px wide, one shared palette, at most GIF_MAX),
// otherwise the PNG sequence is left and the script says so.
//   pnpm build && pnpm capture:demo
// Offline: every request outside the preview server is aborted and fails the capture. The preview server,
// Chrome and ffmpeg are always cleaned up (scripts/browser/session.mjs; ffmpeg runs to completion synchronously).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { settled } from './browser/redesign-checks.mjs';
import { launchChrome, ORIGIN, ROOT, runSession, startPreview } from './browser/session.mjs';

const OUT = join(ROOT, 'docs', 'media', 'demo');
const GIF = join(ROOT, 'docs', 'media', 'demo.gif');
const VIEWPORT = { width: 1280, height: 800 };
const GIF_MAX = 1024 * 1024; // small for the README (docs.test.mjs holds every demo.gif under 4 MB)
/** The load sequence's frames, in ms after the switch (the last stop disc has popped by about 1.3 s). */
const SEQUENCE = [0, 60, 120, 180, 260, 340, 450, 550, 650, 750, 850, 950, 1050, 1150, 1300];
const HOLD = 2; // seconds a frame at rest is held
const expect = (ok, message) => {
  if (!ok) throw new Error(message);
};

await runSession('capture-demo', async () => {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  await startPreview();
  const browser = await launchChrome();
  const context = await browser.newContext({ viewport: VIEWPORT, serviceWorkers: 'block' });
  const blocked = [];
  await context.route('**/*', (route) => {
    const url = route.request().url();
    if (new URL(url).origin === ORIGIN) return route.continue();
    blocked.push(url);
    return route.abort('blockedbyclient');
  });
  // No Worker behind the preview server: health answers as a Worker without AI, so all prose is deterministic.
  await context.route(`${ORIGIN}/api/health`, (route) => route.fulfill({ json: { ok: true, ai: false } }));
  const page = await context.newPage();
  page.setDefaultTimeout(Number(process.env.CHECK_TIMEOUT_MS || 30_000));
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'no-preference' });
  const frames = [];
  const frame = async (what, seconds) => {
    const path = join(OUT, `${String(frames.length + 1).padStart(3, '0')}.png`);
    await page.screenshot({ path });
    frames.push({ path, seconds });
    console.log(`  ${path.slice(ROOT.length + 1)}  ${seconds} s  ${what}`);
  };
  /** Scrolls the page so `selector`'s top sits `offset` px below the window's top. */
  const scrollTo = (selector, offset) => page.evaluate(([sel, off]) => window.scrollTo(0, document.querySelector(sel).getBoundingClientRect().top + window.scrollY - off), [selector, offset]);

  // 1. The load sequence: from Petstore at rest, switch to the Tasks API sample.
  await page.goto(`${ORIGIN}/?sample=petstore`);
  await page.locator('.skill-browser[data-ready="true"]').waitFor({ state: 'attached' });
  await page.evaluate(() => document.fonts.ready);
  await settled(page);
  await scrollTo('#result', 8);
  await page.mouse.move(1, 1);
  // Clicked in the page, so the window stays on the map (the samples sit in the hero above it).
  await page.getByRole('radio', { name: 'Tasks API' }).evaluate((radio) => radio.click());
  await page.locator('#result-title', { hasText: /^Tasks API$/ }).waitFor();
  await page.locator('.skill-browser[data-ready="true"]').waitFor({ state: 'attached' });
  await page.evaluate(() => document.getAnimations().forEach((a) => a.pause()));
  await scrollTo('#result', 8);
  for (const [i, ms] of SEQUENCE.entries()) {
    const n = await page.evaluate((time) => {
      const list = document.getAnimations().filter((a) => a.effect?.getTiming().iterations !== Infinity);
      for (const a of list) a.currentTime = time;
      return list.length;
    }, ms);
    expect(n > 0, `${ms} ms: no animation to seek (the load sequence did not start)`);
    await frame(`load sequence at ${ms} ms (${n} animations)`, ((SEQUENCE[i + 1] ?? ms + 100) - ms) / 1000);
  }
  await page.evaluate(() => document.getAnimations().forEach((a) => a.play()));
  await settled(page);
  await frame('Tasks API at rest', HOLD);

  // 2. Hover getTask: its links, the faded rest and the operation card.
  await page.locator('.op[data-op="getTask"]').hover();
  await page.getByTestId('op-preview').waitFor();
  await settled(page);
  await frame('getTask hovered, its operation card', HOLD * 1.5);

  // 3. In skill: the card's link opens the operation's reference page in the skill browser.
  await page.getByTestId('op-preview').locator('.oc-ref').click();
  await page.locator('.sb-preview .fname', { hasText: /tasks\.md$/ }).waitFor();
  await page.mouse.move(1, 1);
  await page.getByTestId('op-preview').waitFor({ state: 'detached' }); // the preview goes 150 ms after the pointer
  await scrollTo('.skill-browser', 24);
  await settled(page);
  await frame('references/tasks.md in the skill browser, beside the audit', HOLD * 1.5);

  await context.close();
  if (blocked.length) throw new Error(`blocked off-origin requests:\n${blocked.join('\n')}`);
  console.log(`${frames.length} frames in ${OUT.slice(ROOT.length + 1)}/`);

  // The GIF: each frame held its time, 960 px wide, one palette for all frames.
  if (spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' }).status !== 0) {
    console.log('ffmpeg not found: left the PNG sequence only (no demo.gif)');
    return;
  }
  const list = join(OUT, 'frames.txt');
  writeFileSync(list, `${frames.flatMap((f) => [`file '${f.path}'`, `duration ${f.seconds}`]).join('\n')}\nfile '${frames.at(-1).path}'\n`);
  const filter = 'fps=20,scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=64:stats_mode=diff[p];[b][p]paletteuse=dither=none:diff_mode=rectangle';
  const ff = spawnSync('ffmpeg', ['-y', '-v', 'error', '-f', 'concat', '-safe', '0', '-i', list, '-vf', filter, '-loop', '0', GIF], { encoding: 'utf8', timeout: 300_000 });
  if (ff.status !== 0) throw new Error(`ffmpeg failed (${ff.status ?? ff.signal}):\n${ff.stderr}`);
  const size = statSync(GIF).size;
  if (size > GIF_MAX) {
    rmSync(GIF);
    throw new Error(`demo.gif is ${(size / 1024).toFixed(0)} KB (over ${GIF_MAX / 1024} KB): removed; the PNG frames are in ${OUT.slice(ROOT.length + 1)}/`);
  }
  console.log(`wrote ${GIF.slice(ROOT.length + 1)} (${(size / 1024).toFixed(0)} KB, ${frames.length} frames)`);
  expect(existsSync(GIF), 'demo.gif missing');
});
