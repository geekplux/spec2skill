// The launch demo (docs/LAUNCH.md "Demo scenarios"), captured from the real app on the built-in samples:
//   1. teach-mcp       Filesystem MCP: the skill first, the audit, Download .zip; the downloaded zip is
//                      unzipped and its own `node scripts/audit.mjs .` run here, and its real output shown.
//   2. check-tasks     Tasks API: references/workflows.md, then getTask on the map and its feeds edges by keyboard.
//   3. review-petstore Petstore: the list view, a filter, the deprecated operation, the skill's evals.
// Frames go to docs/media/demo/<scenario>/NNN.png (gitignored; regenerated by this script); with the
// system ffmpeg they are assembled into docs/media/demo.gif (960 px wide, palettegen/paletteuse, <= 4 MB),
// otherwise the PNG sequence is left and the script says so.
//   pnpm build && node scripts/capture-demo.mjs        (wrap in `flock /workspace/gx-projects/logs/browser.lock` on shared machines)
// Offline: every request outside the preview server is aborted and fails the capture. The preview server,
// Chrome and ffmpeg are always cleaned up (scripts/browser/session.mjs; ffmpeg runs to completion synchronously).
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { unzipSync } from 'fflate';
import { launchChrome, ORIGIN, ROOT, runSession, startPreview } from './browser/session.mjs';

const OUT = join(ROOT, 'docs', 'media', 'demo');
const GIF = join(ROOT, 'docs', 'media', 'demo.gif');
const VIEWPORT = { width: 1280, height: 800 };
const GIF_MAX = 4 * 1024 * 1024;
const HOLD = 1.6; // seconds per frame in the GIF; the last frame of each scenario is held twice as long
const expect = (ok, message) => {
  if (!ok) throw new Error(message);
};
const escapeHtml = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

/** A terminal frame for output this script really produced (rendered in the page, no network). */
const terminal = (command, output) => `<!doctype html><meta charset="utf-8"><title>terminal</title>
<body style="margin:0;background:#f6f3ec;display:grid;place-items:center;height:100vh;font:15px/1.5 ui-monospace,monospace">
<main style="width:1040px;background:#1d2329;color:#f1ede4;border-radius:6px;padding:24px 28px;white-space:pre-wrap"><span style="color:#a9c7e8">$ ${escapeHtml(command)}</span>
${escapeHtml(output.trimEnd())}</main></body>`;

await runSession('capture-demo', async () => {
  rmSync(OUT, { recursive: true, force: true });
  await startPreview();
  const browser = await launchChrome();
  const context = await browser.newContext({ viewport: VIEWPORT, serviceWorkers: 'block', acceptDownloads: true });
  const blocked = [];
  await context.route('**/*', (route) => {
    const url = route.request().url();
    if (new URL(url).origin === ORIGIN) return route.continue();
    blocked.push(url);
    return route.abort('blockedbyclient');
  });
  // No Worker behind the preview server: health answers as a Worker without AI, so all prose is deterministic.
  await context.route(`${ORIGIN}/api/health`, (route) => route.fulfill({ json: { ok: true, ai: false } }));
  const page = await context.newPage();
  page.setDefaultTimeout(Number(process.env.CHECK_TIMEOUT_MS || 30_000));
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' });
  const frames = [];
  let scenario = '';
  const frame = async (what) => {
    await page.mouse.move(1, 1);
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(150);
    const dir = join(OUT, scenario);
    mkdirSync(dir, { recursive: true });
    const path = join(dir, `${String(frames.filter((f) => f.scenario === scenario).length + 1).padStart(3, '0')}.png`);
    await page.screenshot({ path });
    frames.push({ scenario, path });
    console.log(`  ${path.slice(ROOT.length + 1)}  ${what}`);
  };
  const open = async (sample, hash = '') => {
    await page.goto(`${ORIGIN}/?sample=${sample}${hash}`);
    await page.locator('.skill-pane[data-ready="true"]').waitFor({ state: 'attached' });
    await page.locator('[data-testid="atlas"][data-ready="true"]').waitFor({ state: 'attached' }).catch(() => {});
  };
  const file = async (path) => {
    const item = page.locator(`[role="treeitem"][data-path="${path}"]`);
    if (!(await item.isVisible())) await page.locator(`[role="treeitem"][data-path="${dirname(path)}/"]`).click();
    await item.click();
    await page.locator('#file-head').filter({ hasText: path.split('/').at(-1) }).waitFor();
  };

  // 1. Teach my agent this MCP server.
  scenario = '1-teach-mcp';
  console.log(`scenario ${scenario}`);
  await open('filesystem');
  await frame('first view: the filesystem-mcp skill beside the map');
  await page.locator('.audit > summary').click();
  await frame('the audit rows');
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download .zip' }).click()]);
  expect(download.suggestedFilename() === 'filesystem-mcp-skill.zip', `download named ${download.suggestedFilename()}`);
  await page.getByText('Downloaded filesystem-mcp-skill.zip').first().waitFor();
  await frame('Download .zip');
  const work = mkdtempSync(join(tmpdir(), 'spec2skill-demo-'));
  try {
    const zip = join(work, download.suggestedFilename());
    await download.saveAs(zip);
    for (const [path, bytes] of Object.entries(unzipSync(readFileSync(zip)))) {
      if (path.endsWith('/')) continue;
      mkdirSync(dirname(join(work, path)), { recursive: true });
      writeFileSync(join(work, path), bytes);
    }
    const skill = join(work, 'filesystem-mcp');
    const audit = execFileSync(process.execPath, ['scripts/audit.mjs', '.'], { cwd: skill, encoding: 'utf8', timeout: 120_000 });
    expect(audit.trimEnd().endsWith('audit passed'), `the downloaded skill's audit:\n${audit}`);
    await page.setContent(terminal('unzip filesystem-mcp-skill.zip && cd filesystem-mcp && node scripts/audit.mjs .', audit));
    await frame('the downloaded skill audits itself');
  } finally {
    rmSync(work, { recursive: true, force: true });
  }

  // 2. Check what the skill teaches.
  scenario = '2-check-tasks';
  console.log(`scenario ${scenario}`);
  await open('tasks');
  await file('references/workflows.md');
  await frame('references/workflows.md: the inferred workflows');
  await page.locator('.hit[data-op="getTask"]').focus();
  await page.keyboard.press('Enter');
  await page.getByTestId('detail').waitFor();
  await page.locator('.hit[data-op="getTask"]').focus();
  await frame('getTask focused on the map, its details open');
  await page.keyboard.press('e');
  await page.locator('.atlas .edge[data-cycled]').waitFor({ state: 'attached' });
  await frame('E highlights the first edge');
  await page.keyboard.press('e');
  await frame('E again: the next edge');

  // 3. Review a spec.
  scenario = '3-review-petstore';
  console.log(`scenario ${scenario}`);
  await page.goto(`${ORIGIN}/?sample=petstore&view=list`);
  await page.getByTestId('list-view').waitFor();
  await frame('the list view: every operation and relationship in words');
  await page.locator('.filters > summary').click();
  await page.getByRole('checkbox', { name: 'GET' }).uncheck();
  await frame('Filters: GET off');
  await page.getByRole('button', { name: 'Show all' }).click();
  await page.locator('.filters > summary').click();
  await page.getByLabel(/^Search operations$/).fill('findPetsByTags');
  await page.locator('tr[data-op="findPetsByTags"]').waitFor();
  await frame('search: the deprecated findPetsByTags');
  await file('evals/evals.json');
  await frame("the skill's evals");

  await context.close();
  if (blocked.length) throw new Error(`blocked off-origin requests:\n${blocked.join('\n')}`);
  console.log(`${frames.length} frames in ${OUT.slice(ROOT.length + 1)}/`);

  // The GIF: each frame held HOLD s (a scenario's last frame 2x), 960 px wide, one shared palette.
  if (spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' }).status !== 0) {
    console.log('ffmpeg not found: left the PNG sequence only (no demo.gif)');
    return;
  }
  const list = join(OUT, 'frames.txt');
  const lines = frames.flatMap((f, i) => {
    const last = i === frames.length - 1 || frames[i + 1].scenario !== f.scenario;
    return [`file '${f.path}'`, `duration ${last ? HOLD * 2 : HOLD}`];
  });
  writeFileSync(list, `${lines.join('\n')}\nfile '${frames.at(-1).path}'\n`);
  const filter = 'fps=5,scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=96:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=5:diff_mode=rectangle';
  const ff = spawnSync('ffmpeg', ['-y', '-v', 'error', '-f', 'concat', '-safe', '0', '-i', list, '-vf', filter, '-loop', '0', GIF], { encoding: 'utf8', timeout: 300_000 });
  if (ff.status !== 0) throw new Error(`ffmpeg failed (${ff.status ?? ff.signal}):\n${ff.stderr}`);
  const size = statSync(GIF).size;
  if (size > GIF_MAX) {
    rmSync(GIF);
    throw new Error(`demo.gif is ${(size / 1048576).toFixed(1)} MB (> 4 MB): removed; the PNG frames are in ${OUT.slice(ROOT.length + 1)}/`);
  }
  console.log(`wrote ${GIF.slice(ROOT.length + 1)} (${(size / 1024).toFixed(0)} KB, ${frames.length} frames)`);
  expect(existsSync(GIF), 'demo.gif missing');
});
